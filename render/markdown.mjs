// README table and EVIDENCE.md, both generated from data/clients.yaml
import { COLUMNS, GROUPS, TIERS, MIN_ISSUES, protocolGrade, formatDate } from './data.mjs';

const KIND = { cli: 'CLI', app: 'App or IDE' };
const MARK = { y: '✅', p: '🟡', n: '❌' };
const GRADE = { g: '🟢', a: '🟠', rd: '🔴', x: '⚪' };
const cellText = (key, cell, versions) => {
  if (key === 'protocol') return `${GRADE[protocolGrade(cell.value, versions)]} ${cell.value}${cell.fallback ? ` (falls back to ${cell.fallback})` : ''}`;
  if (key === 'tool_search' && cell.value === 'y' && cell.label) return `${MARK.y} ${cell.label}`;
  return MARK[cell.value];
};
const pipe = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
// Link text and URL both land inside a table cell, so neither may carry a raw pipe, bracket or newline
const link = (text, url) => `[${pipe(text).replace(/[[\]]/g, '\\$&')}](${encodeURI(decodeURI(url)).replace(/\|/g, '%7C').replace(/\)/g, '%29')})`;
const fixText = f => (f.kind === 'rate' ? `${f.pct}% of ${f.n}` : f.kind === 'few' ? 'too few issues' : 'no public tracker');
const anchor = name => name.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-');

export function readmeTable({ data }) {
  const out = [];
  for (const [g, label] of GROUPS) {
    out.push(`### ${label}`, '');
    out.push(`| Tier | Client | Checked on | MCP bugs fixed | ${COLUMNS.map(([, l]) => l).join(' | ')} |`);
    out.push(`|${' --- |'.repeat(4 + COLUMNS.length)}`);
    const rows = data.clients.filter(c => c.group === g).sort((a, b) => TIERS.indexOf(a.tier) - TIERS.indexOf(b.tier));
    for (const c of rows) {
      const cells = COLUMNS.map(([k]) => link(cellText(k, c.cells[k], data.spec_versions), c.cells[k].source));
      const tracker = c.tracker ? `[${fixText(c.fix)}](https://github.com/${c.tracker.repo}/issues)` : fixText(c.fix);
      out.push(`| **${c.tier}** | [${pipe(c.name)}](EVIDENCE.md#${anchor(c.name)}) | ${c.version_checked ? '`' + pipe(c.version_checked) + '`' : 'hosted'} | ${tracker} | ${cells.join(' | ')} |`);
    }
    out.push('');
  }
  const notes = data.clients.filter(c => c.note).map(c => `- **${c.name}**: ${c.note}`);
  if (notes.length) out.push(...notes, '');
  return out.join('\n');
}

export function evidence({ data }) {
  const out = [
    '# Evidence',
    '',
    '<!-- Generated by `npm run build` from data/clients.yaml. Do not edit by hand. -->',
    '',
    `Every cell in the [README](README.md) table, with the source it was checked against. As of ${formatDate(data.as_of)}.`,
    '',
    'Methods: `probe` is a live handshake against a local MCP server (see [probe/](probe/)), `source` is the client\'s own code at a pinned commit or published package, `docs` and `changelog` are the vendor\'s pages, `issue` is a GitHub issue or pull request.',
    '',
  ];
  for (const c of data.clients) {
    out.push(`## ${c.name}`, '');
    const meta = [`Tier **${c.tier}**`, KIND[c.group]];
    if (c.version_checked) meta.push(`checked on \`${c.version_checked}\``);
    if (c.tracker) meta.push(`tracker [${c.tracker.repo}](https://github.com/${c.tracker.repo}/issues)`);
    meta.push(`MCP bugs fixed: ${fixText(c.fix)}`);
    out.push(meta.join(' · '), '');
    if (c.note) out.push(`> ${c.note}`, '');
    out.push('| Feature | Value | Evidence | Method | Checked |', '| --- | --- | --- | --- | --- |');
    for (const [k, l] of COLUMNS) {
      const cell = c.cells[k];
      out.push(`| ${l} | ${link(cellText(k, cell, data.spec_versions), cell.source)} | ${pipe(cell.evidence)} | ${cell.method} | ${cell.checked} |`);
    }
    out.push('');
  }
  out.push(`MCP bugs fixed is completed issues divided by issues minus duplicates, for issues opened since ${data.bug_window_start} with "mcp" in the title. Below ${MIN_ISSUES} issues the rate is not shown. Counts are in [data/bugs.json](data/bugs.json).`, '');
  return out.join('\n');
}

export const MARKERS = ['<!-- table:start -->', '<!-- table:end -->'];
export function spliceReadme(readme, table, data) {
  const [a, b] = MARKERS;
  const i = readme.indexOf(a), j = readme.indexOf(b);
  if (i < 0 || j < i) throw new Error(`README.md needs ${a} and ${b} markers`);
  const stamp = `<!-- Generated by \`npm run build\` from data/clients.yaml. Do not edit between the markers. -->\n\nAs of ${formatDate(data.as_of)}. Click any cell for its source, or a client name for the full evidence.\n\n`;
  return readme.slice(0, i + a.length) + '\n' + stamp + table + readme.slice(j);
}
